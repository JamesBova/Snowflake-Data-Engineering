CREATE OR REPLACE STREAM SNOWFLAKE_DE_LAB.RAW.TRANSACTIONS_STREAM
ON TABLE SNOWFLAKE_DE_LAB.RAW.TRANSACTIONS_CSV;

CREATE OR REPLACE TABLE SNOWFLAKE_DE_LAB.ANALYTICS.TRANSACTIONS_PROCESSED (
    RECORD_ID NUMBER,
    CUSTOMER_ID NUMBER,
    TRANSACTION_DATE DATE,
    AMOUNT NUMBER(10,2),
    TRANSACTION_TYPE VARCHAR,
    PROCESSED_AT TIMESTAMP
);

CREATE OR REPLACE TASK SNOWFLAKE_DE_LAB.RAW.PROCESS_TRANSACTIONS_TASK
    WAREHOUSE = SNOWFLAKE_DE_WH
    SCHEDULE = '1 MINUTE'
WHEN SYSTEM$STREAM_HAS_DATA(
    'SNOWFLAKE_DE_LAB.RAW.TRANSACTIONS_STREAM'
)
AS
INSERT INTO SNOWFLAKE_DE_LAB.ANALYTICS.TRANSACTIONS_PROCESSED
SELECT
    RECORD_ID,
    CUSTOMER_ID,
    TRANSACTION_DATE,
    AMOUNT,
    TRANSACTION_TYPE,
    CURRENT_TIMESTAMP()
FROM SNOWFLAKE_DE_LAB.RAW.TRANSACTIONS_STREAM
WHERE METADATA$ACTION = 'INSERT';

--to enable task
ALTER TASK SNOWFLAKE_DE_LAB.RAW.PROCESS_TRANSACTIONS_TASK RESUME;
--to disable task
ALTER TASK SNOWFLAKE_DE_LAB.RAW.PROCESS_TRANSACTIONS_TASK SUSPEND;