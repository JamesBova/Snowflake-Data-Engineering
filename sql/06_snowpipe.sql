CREATE OR REPLACE TABLE SNOWFLAKE_DE_LAB.RAW.SNOWPIPE_TRANSACTIONS (
    RECORD_ID NUMBER,
    CUSTOMER_ID NUMBER,
    TRANSACTION_DATE DATE,
    AMOUNT NUMBER(10,2),
    TRANSACTION_TYPE VARCHAR
);

CREATE OR REPLACE PIPE SNOWFLAKE_DE_LAB.RAW.TRANSACTIONS_PIPE
AS
COPY INTO SNOWFLAKE_DE_LAB.RAW.SNOWPIPE_TRANSACTIONS
FROM @SNOWFLAKE_DE_LAB.RAW.CSV_STAGE
FILE_FORMAT = (
    FORMAT_NAME = SNOWFLAKE_DE_LAB.RAW.CSV_FORMAT
);

